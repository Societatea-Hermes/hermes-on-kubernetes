#!/usr/bin/env bash
# Regenerates install.yaml from the upstream ArgoCD release manifest, with every
# namespaced resource put in the `argocd` namespace. Upstream leaves namespaces
# out (it expects `kubectl apply -n argocd`), but Talos applies install.yaml as is
# at bootstrap and would put all of ArgoCD in `default`.
#
#   ./update.sh            # regenerate for the version below
#   ./update.sh v3.6.0     # upgrade: bump ARGOCD_VERSION below too, then commit
#
# After the bootstrap, ArgoCD manages itself from ../overlays (which uses this
# file), so upgrading is: run this, commit, push.
set -euo pipefail
cd "$(dirname "$0")"

ARGOCD_VERSION="${1:-v3.5.4}"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

curl -fsSL "https://raw.githubusercontent.com/argoproj/argo-cd/${ARGOCD_VERSION}/manifests/install.yaml" \
  -o "$tmp/upstream.yaml"
cat > "$tmp/kustomization.yaml" <<YAML
namespace: argocd
resources:
  - upstream.yaml
YAML

{
  echo "# Generated by update.sh from ArgoCD ${ARGOCD_VERSION}. Don't edit by hand."
  kubectl kustomize "$tmp"
} > install.yaml

echo "Wrote install.yaml (ArgoCD ${ARGOCD_VERSION})"
